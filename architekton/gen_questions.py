"""Generate the catalog-owned question files.

Sources: meta/catalog.yml + meta/questionnaire/.

meta/questionnaire/tree.yml lists which questions/*.yml files are
generated (areas) and where each template variant's follow-up questions
plug in (plugs_in). Each area source (meta/questionnaire/areas/<out>) is
plain YAML plus two markers:

  # !fragment <path>   splice meta/questionnaire/fragments/<path>.yml
                     verbatim — shared questions (log_library today) live
                     in one fragment, so types reuse them instead of
                     restating the block.
  # !catalog  <name>   emit a question built from meta/catalog.yml —
                     `ros_distro` is the slot: choices, label, default and
                     help all derive from [python.ros] rows, so adding a
                     distro = one catalog row + one tree row.

The generated files are written deterministically (markers are expanded
line-wise, never through a YAML round-trip), so --check is a
byte-for-byte drift test.

`--write` regenerates in place; the default is a drift check that exits 1
when a checked-in output is stale, matching gen_macros.py's convention.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

TOP = Path(__file__).resolve().parent.parent
CATALOG = TOP / "meta" / "catalog.yml"
TREE = TOP / "meta" / "questionnaire" / "tree.yml"
AREAS = TOP / "meta" / "questionnaire" / "areas"
FRAGMENTS = TOP / "meta" / "questionnaire" / "fragments"
QUESTIONS = TOP / "questions"

GENERATED_NOTE = (
    "# GENERATED by architekton/gen_questions.py from meta/catalog.yml +\n"
    "# meta/questionnaire/ — do not edit; run `task regen`.\n"
)


def ros_distro(catalog: dict) -> str:
    """The ros_distro question, built from [python.ros] catalog rows."""
    ros = catalog["python"]["ros"]
    distros = list(ros)
    default = next((n for n, d in ros.items() if d.get("default")), distros[0])
    bullets = "; ".join(f"{d['label']} is {d['description']}" for d in ros.values() if d.get("description"))
    choices = "\n".join(f"        {d['label']}: {name}" for name, d in ros.items())
    return f"""ros_distro:
    type: str
    when: "{{{{ project_type == 'ros2' }}}}"
    help: |
        ROS 2 distribution. {bullets}.
    choices:
{choices}
    default: {default}
"""


CATALOG_SLOTS = {"ros_distro": ros_distro}


def render_area(source: Path, catalog: dict) -> str:
    """Expand !fragment/!catalog markers in one area source file."""
    out: list[str] = []
    for line in source.read_text(encoding="utf-8").splitlines():
        if line.startswith("# !fragment "):
            name = line.split(None, 2)[2].strip()
            frag = FRAGMENTS / f"{name}.yml"
            out.append(frag.read_text(encoding="utf-8").rstrip("\n"))
        elif line.startswith("# !catalog "):
            name = line.split(None, 2)[2].strip()
            out.append(CATALOG_SLOTS[name](catalog).rstrip("\n"))
        else:
            out.append(line)
    return "\n".join(out).rstrip("\n") + "\n"


def outputs(catalog: dict, tree: dict) -> dict[Path, str]:
    return {QUESTIONS / out: GENERATED_NOTE + "\n" + render_area(AREAS / out, catalog) for out in tree["areas"]}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate in place")
    args = parser.parse_args()

    catalog = yaml.safe_load(CATALOG.read_text(encoding="utf-8"))
    tree = yaml.safe_load(TREE.read_text(encoding="utf-8"))
    rendered = outputs(catalog, tree)

    stale = [p for p, want in rendered.items() if not p.exists() or p.read_text(encoding="utf-8") != want]
    if args.write:
        for p, want in rendered.items():
            p.write_text(want, encoding="utf-8")
            print(f"wrote {p.relative_to(TOP)}")
        return 0
    if stale:
        names = ", ".join(str(p.relative_to(TOP)) for p in stale)
        print(f"drift: {names} stale; run `task regen`", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

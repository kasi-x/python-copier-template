"""Generate partials/macros.jinja from meta/catalog.yml.

The catalog is the root: it holds the version facts the template needs,
each next to its update policy (`update = "bot"` — a bot may bump it;
`update = "pinned"` — a human must). This script renders the Jinja macros
templates consume (`m.python_version()`, `m.classifiers()`,
`m.experiment_pep508()`, `m.experiment_pixi()`) from that one file, so the
values are written exactly once — in TOML — and every renderer sees the
same facts.

`--write` regenerates in place; the default is a drift check that exits 1
when the checked-in output is stale, matching gen_docs.py's convention.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

TOP = Path(__file__).resolve().parent.parent
CATALOG = TOP / "meta" / "catalog.yml"
OUT = TOP / "partials" / "macros.jinja"

HEADER = """{# GENERATED by architekton/gen_macros.py from meta/catalog.yml — do not
   edit this file; edit the catalog and run `task regen`.
   Update policy lives next to each value there: `update = "bot"` is fair
   game for an automated bump, `update = "pinned"` (e.g. ROS distro pins,
   ABI-locked by REP-2000) must not move without a human.

   Single-source facts that several render paths would otherwise duplicate.
   Import where needed:

       {% import "partials/macros.jinja" as m with context %}

   and call `m.run_prefix()` / `m.python_version()` / `m.classifiers()` /
   `m.experiment_pep508()` / `m.experiment_pixi()`.
   Never paste the literal values back into a consumer: each fact is written
   exactly once, in the catalog. #}"""

BODY_STATIC = """{% for name, spec in EXPERIMENT_PAIRS %}    "{{ name }}{{ spec }}",
{% endfor %}
{%- endmacro %}
{% macro experiment_pixi() -%}
{% for name, spec in EXPERIMENT_PAIRS %}{{ name }} = "{{ spec if spec else '*' }}"
{% endfor %}
{%- endmacro %}
{% macro run_prefix() -%}{{
    'uv run --locked ' if package_manager == 'uv'
    else ('pixi run -e dev --locked ' if package_manager == 'pixi' else 'poetry run ')
}}{%- endmacro %}
"""


def render(catalog: dict) -> str:
    """Render macros.jinja from the parsed catalog."""
    exp = catalog["experiment_deps"]
    pairs = ",\n".join(f'    ("{d["name"]}", "{d["spec"]}")' for d in exp)

    ros = catalog["python"]["ros"]
    floor = catalog["python"]["floor"]["version"]
    distros = list(ros)
    # Nested else form: 'v0' if cond0 else ('v1' if cond1 else ... 'floor').
    # The innermost else is bare and closes the surrounding '(' — that
    # trailing `else 'X.Y')` is what check_upstream.py's floor pin regexes.
    expr = ""
    for i, name in enumerate(reversed(distros)):
        cond = f"ros2_pkg and ros_distro == '{name}'"
        expr = (
            f"'{ros[name]['version']}' if {cond} else '{floor}'"
            if i == 0
            else f"'{ros[name]['version']}' if {cond} else ({expr})"
        )
    python_version_expr = "{{ " + expr + " }}"

    classifiers = "\n".join(f"    '\"{c}\",'" for c in catalog["classifiers"]["non_ros"])
    # One single-version classifier list per distro, nested the same way as
    # python_version(): a new catalog row gets its own branch without the
    # two-distro hardcode the hand-written macro had.
    cls_expr = f"[\n{classifiers}\n    ]"
    for name in reversed(distros):
        cond = f"ros2_pkg and ros_distro == '{name}'"
        cls_expr = (
            f"['\"Programming Language :: Python :: {ros[name]['version']}\",']"
            f"\n    if {cond} else (\n    {cls_expr}\n    )"
        )
    classifiers_block = (
        "{% macro classifiers() -%}\n"
        "{%- set lines = " + cls_expr + " -%}\n" + "{{ lines | join('\\n    ') ~ '\\n    ' }}\n" + "{%- endmacro %}\n"
    )

    return (
        HEADER
        + "\n{% set EXPERIMENT_PAIRS = [\n"
        + pairs
        + "\n] %}\n"
        + "{% macro experiment_pep508() -%}\n"
        + BODY_STATIC
        + "{% macro python_version() -%}"
        + python_version_expr
        + "{%- endmacro %}\n"
        + classifiers_block
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate in place")
    args = parser.parse_args()

    catalog = yaml.safe_load(CATALOG.read_text(encoding="utf-8"))
    rendered = render(catalog)
    if args.write:
        OUT.write_text(rendered, encoding="utf-8")
        print(f"wrote {OUT.relative_to(TOP)}")
        return 0
    if OUT.read_text(encoding="utf-8") != rendered:
        print(f"drift: {OUT.relative_to(TOP)} is stale; run `task regen`", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

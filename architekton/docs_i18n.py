#!/usr/bin/env python3
"""Stage a translated docs site: docs-i18n/<lang>/ -> build/docs-i18n/<lang>/.

The English pages under docs/ are the source of truth. A translation lives
in docs-i18n/<lang>/ and mirrors docs/ path for path: docs-i18n/ja/how-to/adopt.md
translates docs/how-to/adopt.md. Translations are written by orimono's Lattice
Docs (`lattice docs sync`, layout "docs-i18n/{lang}/{path}") or by hand --
never by this script, which only assembles a buildable tree from them.

Why a separate tree and a staged build instead of docs/ja/:

- Zensical renders exactly one language per build (one `theme.language`),
  so every language is its own site.
- Zensical 0.0.57 has no `exclude_docs`: anything under docs/ is rendered
  into the English site, so translations cannot live there.
- Zensical refuses a `site_dir` outside the config file's directory, so the
  staged config builds into build/docs-i18n/<lang>/site.

What gets staged in build/docs-i18n/<lang>/:

- docs/: every non-Markdown file of docs/ (images, data), so a translated
  page's relative links to them resolve, then docs-i18n/<lang>/ on top. An
  untranslated page is simply absent: the site carries translated pages only.
- zensical.toml: the root config with `docs_dir`, `site_dir`, `edit_uri` and
  `theme.language` replaced, and `nav` reduced to the translated pages. A
  page's nav label is its first `# ` heading; a section's label is the
  heading of its first translated page (the section's overview page, whose
  heading is the section name). Nav labels live in zensical.toml, not in any
  page, so deriving them keeps one source for each translated string.

Exit 1 when docs-i18n/<lang>/ has no Markdown pages yet.

Usage:
    python architekton/docs_i18n.py ja
    zensical build -f build/docs-i18n/ja/zensical.toml
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import tomlkit

TOP = Path(__file__).resolve().parent.parent
HEADING = re.compile(r"^# +(.+?)\s*#*\s*$")
FENCE = re.compile(r"^\s*(```|~~~)")
GENERATED_NOTE = "Generated by architekton/docs_i18n.py from zensical.toml -- do not edit; re-run the script."


@dataclass(frozen=True)
class Staged:
    stage: Path
    pages: int
    nav_pages: int


def first_heading(page: Path) -> str | None:
    """The page's first ATX level-1 heading outside code fences, if any."""
    in_fence = False
    for line in page.read_text(encoding="utf-8").splitlines():
        if FENCE.match(line):
            in_fence = not in_fence
            continue
        if not in_fence and (match := HEADING.match(line)):
            return match.group(1)
    return None


def reduce_nav(nav: list[dict[str, Any]], translated: Path) -> list[dict[str, Any]]:
    """`nav` keeping only pages present under `translated`, relabelled by heading."""
    reduced: list[dict[str, Any]] = []
    for entry in nav:
        for label, target in entry.items():
            if isinstance(target, str):
                page = translated / target
                if page.is_file():
                    reduced.append({first_heading(page) or label: target})
            else:
                children = reduce_nav(target, translated)
                if children:
                    section = next(iter(children[0]))
                    reduced.append({section: children})
    return reduced


def count_pages(nav: list[dict[str, Any]]) -> int:
    return sum(1 if isinstance(target, str) else count_pages(target) for entry in nav for target in entry.values())


class NoTranslationsError(Exception):
    """docs-i18n/<lang>/ holds no Markdown page to build."""


def stage(top: Path, lang: str) -> Staged:
    translated = top / "docs-i18n" / lang
    pages = sorted(translated.rglob("*.md")) if translated.is_dir() else []
    if not pages:
        msg = (
            f"docs-i18n/{lang}/ has no Markdown pages yet: translate a page of docs/ "
            f"to the same relative path under docs-i18n/{lang}/ first."
        )
        raise NoTranslationsError(msg)

    out = top / "build" / "docs-i18n" / lang
    docs = out / "docs"
    if docs.exists():
        shutil.rmtree(docs)
    source = top / "docs"
    for asset in source.rglob("*"):
        if asset.is_file() and asset.suffix != ".md":
            target = docs / asset.relative_to(source)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(asset, target)
    shutil.copytree(translated, docs, dirs_exist_ok=True)

    config = tomllib.loads((top / "zensical.toml").read_text(encoding="utf-8"))
    project = config["project"]
    nav = reduce_nav(project.get("nav", []), translated)
    project["docs_dir"] = "docs"
    project["site_dir"] = "site"
    project["edit_uri"] = f"edit/main/docs-i18n/{lang}/"
    project["theme"]["language"] = lang
    project["nav"] = nav
    out.mkdir(parents=True, exist_ok=True)
    (out / "zensical.toml").write_text(f"# {GENERATED_NOTE}\n{tomlkit.dumps(config)}", encoding="utf-8")
    return Staged(stage=out, pages=len(pages), nav_pages=count_pages(nav))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Stage a translated docs site: docs-i18n/<lang>/ -> build/docs-i18n/<lang>/."
    )
    parser.add_argument("lang", help="language code, the directory name under docs-i18n/ (e.g. ja)")
    args = parser.parse_args(argv)
    try:
        staged = stage(TOP, args.lang)
    except NoTranslationsError as error:
        print(error, file=sys.stderr)
        return 1
    rel = staged.stage.relative_to(TOP)
    print(f"Staged {staged.pages} translated page(s) ({staged.nav_pages} in nav) into {rel}/")
    print(f"Build: zensical build -f {rel}/zensical.toml")
    return 0


if __name__ == "__main__":
    sys.exit(main())

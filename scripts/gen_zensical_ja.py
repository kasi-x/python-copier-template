#!/usr/bin/env python3
"""Generate zensical.ja.toml from zensical.toml for the docs-i18n/ja layout.

The Lattice Docs pipeline renders translated pages into
``docs-i18n/ja/{path}``. The Japanese site is a second zensical build whose
``docs_dir`` points there; everything else in the config is copied verbatim
except:

* ``nav`` is derived from each translated page's first ``#`` heading when the
  page exists (the Lattice design's A2 nav-adapter is deferred, so untranslated
  nav titles keep their English label), and nav paths stay page-relative.
* ``site_dir`` becomes ``site/ja``.
* ``site_name``/``site_description``/``site_author`` carry over (config
  strings are not Markdown and stay untranslated in v1).
* ``edit_uri`` is dropped — translated files are generated, not edited on
  GitHub directly.

Run ``task docs-ja-config`` (or ``task docs-ja`` which depends on it).
"""

from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

import tomli_w

ROOT = Path(__file__).resolve().parents[1]
SRC_TOML = ROOT / "zensical.toml"
OUT_TOML = ROOT / "zensical.ja.toml"
JA_DOCS = ROOT / "docs-i18n" / "ja"


def _title_for(page: str, fallback: str) -> str:
    """First ``# …`` heading of the rendered ja page, else the en label."""
    path = JA_DOCS / page
    if not path.is_file():
        return fallback
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^#\s+(.+?)\s*$", line)
        if m:
            return m.group(1).replace("\\", "\\\\").replace('"', '\\"')
    return fallback


def _ja_nav(node) -> str:
    """Re-emit zensical's nav structure with translated titles.

    ``nav`` is a list of ``{label = path}`` tables (possibly nested lists).
    We keep the shape byte-for-byte and only translate leaf labels.
    """
    if isinstance(node, list):
        inner = ",\n".join(_ja_nav(x) for x in node)
        return f"[\n{inner}\n]"
    if isinstance(node, dict):
        assert len(node) == 1, f"nav entries are single-key tables: {node!r}"
        ((label, value),) = node.items()
        if isinstance(value, str):
            title = _title_for(value, label)
            return f'{{ "{title}" = "{value}" }}'
        return f'{{ "{label}" = {_ja_nav(value)} }}'
    msg = f"unexpected nav node: {node!r}"
    raise TypeError(msg)


def _toml_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    cfg = tomllib.loads(SRC_TOML.read_text(encoding="utf-8"))
    proj = cfg["project"]

    out: list[str] = [
        "[project]",
        "# GENERATED by scripts/gen_zensical_ja.py — edit zensical.toml, then `task docs-ja-config`.",
    ]
    out.extend(
        f"{key} = {_toml_str(proj[key])}" for key in ("site_name", "site_description", "site_author") if key in proj
    )
    out.extend(f"{key} = {_toml_str(proj[key])}" for key in ("repo_url", "repo_name", "copyright") if key in proj)
    out.append('site_dir = "site/ja"')
    out.append('docs_dir = "docs-i18n/ja"')
    if "nav" in proj:
        out.append("nav = " + _ja_nav(proj["nav"]))

    theme = {k: v for k, v in proj.get("theme", {}).items() if k != "language"}
    if theme:
        out.append("\n[project.theme]")
        out.append(tomli_w.dumps(theme).strip())
    if proj.get("theme", {}).get("language"):
        out.append('language = "ja"')

    tail = {s_: proj[s_] for s_ in ("plugins", "markdown_extensions") if s_ in proj}
    if tail:
        out.append("\n" + tomli_w.dumps(tail).strip())

    OUT_TOML.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT_TOML} (docs_dir=docs-i18n/ja, site_dir=site/ja)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
